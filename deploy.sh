#!/usr/bin/env bash
# ============================================================================
#  INCONNU SMS — one-command VPS deployment
#  Your Numbers. Your World.  —  BY INCONNU BOY SENSEI
#
#  Usage (Ubuntu/Debian VPS, as root):
#    ./deploy.sh                                   # HTTP on the server IP
#    ./deploy.sh --domain sms.example.com --email you@example.com   # + free HTTPS (Let's Encrypt)
#  Options:
#    --admin-email <email>    Super admin login (default: admin@<domain>)
#    --admin-password <pw>    Super admin password (default: random, printed at the end)
#    --no-demo                Disable the DEMO provider on first install
#  Re-running the script updates the app (git pull + rebuild); data is kept.
# ============================================================================
set -euo pipefail

DOMAIN=""; EMAIL=""; ADMIN_EMAIL=""; ADMIN_PASSWORD=""; DEMO="true"
REPO_URL="${REPO_URL:-}"; INSTALL_DIR="${INSTALL_DIR:-/opt/inconnu-sms}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --email) EMAIL="$2"; shift 2 ;;
    --admin-email) ADMIN_EMAIL="$2"; shift 2 ;;
    --admin-password) ADMIN_PASSWORD="$2"; shift 2 ;;
    --no-demo) DEMO="false"; shift ;;
    *) echo "Unknown option $1"; exit 1 ;;
  esac
done

c_violet="\033[38;5;135m"; c_ok="\033[32m"; c_dim="\033[2m"; c_off="\033[0m"
step() { echo -e "${c_violet}▶${c_off} $*"; }
ok() { echo -e "${c_ok}✔${c_off} $*"; }

[[ $EUID -eq 0 ]] || { echo "Please run as root (sudo ./deploy.sh …)"; exit 1; }

# 1) Get the code when the script is piped from the internet
if [[ ! -f docker-compose.yml ]]; then
  [[ -n "$REPO_URL" ]] || { echo "Run this script from the project folder, or set REPO_URL=<git url>."; exit 1; }
  command -v git >/dev/null || (apt-get update -y && apt-get install -y git)
  if [[ -d "$INSTALL_DIR/.git" ]]; then git -C "$INSTALL_DIR" pull --ff-only; else git clone "$REPO_URL" "$INSTALL_DIR"; fi
  cd "$INSTALL_DIR"
elif [[ -d .git ]]; then
  git pull --ff-only 2>/dev/null || true
fi

# 2) Docker
if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
  step "Installing Docker…"
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi
ok "Docker $(docker --version | cut -d' ' -f3 | tr -d ',')"

# 3) Firewall (if ufw is present)
if command -v ufw >/dev/null; then ufw allow 22/tcp >/dev/null || true; ufw allow 80/tcp >/dev/null || true; ufw allow 443/tcp >/dev/null || true; fi

# 4) .env with strong random secrets (created once, never overwritten)
rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }
PUBLIC_IP="$(curl -fsS https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
if [[ ! -f .env ]]; then
  step "Generating .env with random secrets…"
  [[ -n "$ADMIN_EMAIL" ]] || ADMIN_EMAIL="admin@${DOMAIN:-inconnu-sms.local}"
  [[ -n "$ADMIN_PASSWORD" ]] || ADMIN_PASSWORD="Is$(rand 18)9"
  APP_URL="http://${DOMAIN:-$PUBLIC_IP}"
  cat > .env <<ENV
# ---- generated by deploy.sh on $(date -u +%FT%TZ) ----
APP_URL=${APP_URL}
DOMAIN=${DOMAIN:-localhost}
APP_SECRET=$(rand 64)
ENCRYPTION_KEY=$(rand 64)
CRON_SECRET=$(rand 48)
POSTGRES_USER=inconnu
POSTGRES_PASSWORD=$(rand 32)
POSTGRES_DB=inconnu_sms
ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}
ADMIN_NAME=Inconnu Boy Sensei
DEMO_PROVIDER=${DEMO}
# Stripe (or configure in Admin → Settings & Stripe)
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=
# SMTP (optional — without it, emails are written to Admin → System logs)
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=INCONNU SMS <no-reply@${DOMAIN:-localhost}>
ENV
  chmod 600 .env
  ok ".env created"
else
  ok ".env already exists — keeping secrets"
  ADMIN_EMAIL="$(grep '^ADMIN_EMAIL=' .env | cut -d= -f2-)"
  ADMIN_PASSWORD="(unchanged — see .env)"
fi

# 5) Nginx in HTTP mode first (needed for the ACME challenge)
mkdir -p docker/certbot/conf docker/certbot/www docker/nginx/templates
cp docker/nginx/app-locations.inc.template docker/nginx/templates/app-locations.inc.template
if [[ -n "$DOMAIN" && -f "docker/certbot/conf/live/$DOMAIN/fullchain.pem" ]]; then
  cp docker/nginx/https.conf.template docker/nginx/templates/default.conf.template
else
  cp docker/nginx/http.conf.template docker/nginx/templates/default.conf.template
fi

# 6) Build & start (migrations + seed run automatically in the app container)
step "Building and starting containers (first build takes a few minutes)…"
docker compose up -d --build
step "Waiting for the application to be healthy…"
for i in $(seq 1 90); do
  if docker compose exec -T app node -e "fetch('http://127.0.0.1:3000/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" >/dev/null 2>&1; then break; fi
  sleep 3
  [[ $i -eq 90 ]] && { docker compose logs --tail 80 app; echo "App did not become healthy"; exit 1; }
done
ok "Application is up — database migrated & seeded"

# 7) HTTPS with Let's Encrypt
if [[ -n "$DOMAIN" && -n "$EMAIL" && ! -f "docker/certbot/conf/live/$DOMAIN/fullchain.pem" ]]; then
  step "Requesting a Let's Encrypt certificate for $DOMAIN…"
  if docker run --rm -v "$PWD/docker/certbot/conf:/etc/letsencrypt" -v "$PWD/docker/certbot/www:/var/www/certbot" \
      certbot/certbot certonly --webroot -w /var/www/certbot -d "$DOMAIN" --email "$EMAIL" --agree-tos --no-eff-email --non-interactive; then
    cp docker/nginx/https.conf.template docker/nginx/templates/default.conf.template
    sed -i "s#^APP_URL=.*#APP_URL=https://${DOMAIN}#" .env
    docker compose up -d --force-recreate app worker nginx
    # auto-renewal twice a day
    cat > /etc/cron.d/inconnu-sms-certbot <<CRON
17 3,15 * * * root cd $PWD && docker run --rm -v $PWD/docker/certbot/conf:/etc/letsencrypt -v $PWD/docker/certbot/www:/var/www/certbot certbot/certbot renew --quiet && docker compose exec -T nginx nginx -s reload
CRON
    ok "HTTPS enabled"
  else
    echo "⚠ Certificate request failed (check DNS A record → $PUBLIC_IP). Site stays on HTTP."
  fi
fi

# 8) Daily database backup (kept 14 days)
mkdir -p backups
cat > /etc/cron.d/inconnu-sms-backup <<CRON
30 2 * * * root cd $PWD && docker compose exec -T db pg_dump -U inconnu inconnu_sms | gzip > backups/db-\$(date +\%F).sql.gz && find backups -name 'db-*.sql.gz' -mtime +14 -delete
CRON

URL="$(grep '^APP_URL=' .env | cut -d= -f2-)"
echo
echo -e "${c_violet}════════════════════════════════════════════════════════════${c_off}"
echo -e "  ${c_violet}INCONNU SMS${c_off} is online  →  ${URL}"
echo -e "  Admin panel           →  ${URL}/admin"
echo -e "  Super admin email     →  ${ADMIN_EMAIL}"
echo -e "  Super admin password  →  ${ADMIN_PASSWORD}"
echo -e "  Stripe webhook URL    →  ${URL}/api/webhooks/stripe"
echo -e "${c_dim}  Change the admin password after first login (Dashboard → Settings).${c_off}"
echo -e "${c_dim}  BY INCONNU BOY SENSEI${c_off}"
echo -e "${c_violet}════════════════════════════════════════════════════════════${c_off}"
